#!/usr/bin/env bash
# =============================================================================
# Generate a local .env with cryptographically random secrets.
# Usage:
#   ./scripts/generate-env.sh          # refuses to overwrite
#   ./scripts/generate-env.sh --force  # replace existing .env
# =============================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TARGET="$ROOT/.env"

if [[ -f "$TARGET" && "${1:-}" != "--force" ]]; then
  echo "Refusing to overwrite existing .env. Run with --force to replace it." >&2
  exit 1
fi

if ! command -v openssl >/dev/null 2>&1; then
  echo "openssl is required to generate random secrets." >&2
  exit 1
fi

hex() { openssl rand -hex 32; }
seed_pw() { printf '%s!Aa1%s' "$1" "$(openssl rand -hex 6)"; }

OWNER_PW="$(hex)"
APP_PW="$(hex)"
RO_PW="$(hex)"
POSTGRES_PW="$(hex)"
JWT="$(hex)"
COOKIE="$(hex)"
MFA="$(hex)"
CHALLENGE="$(hex)"
WEBHOOK="$(hex)"
SUPER_PW="$(seed_pw SsimsSuper)"
ADMIN_PW="$(seed_pw SsimsAdmin)"
LECTURER_PW="$(seed_pw SsimsLecturer)"
STUDENT_PW="$(seed_pw SsimsStudent)"
LAB_PW="$(seed_pw SsimsLab)"

umask 077
cat > "$TARGET" <<EOF
# Generated by scripts/generate-env.sh. Never commit this file.
NODE_ENV=development
FRONTEND_ORIGIN=http://localhost:5173
ADDITIONAL_ORIGINS=https://127.0.0.1
PUBLIC_ORIGIN=https://localhost
API_PORT=4000
LOG_LEVEL=info

POSTGRES_DB=ssims
POSTGRES_USER=postgres
POSTGRES_SUPERUSER_PASSWORD=$POSTGRES_PW
POSTGRES_OWNER=ssims_owner
POSTGRES_OWNER_PASSWORD=$OWNER_PW
POSTGRES_APP_USER=ssims_app
POSTGRES_APP_PASSWORD=$APP_PW
POSTGRES_RO_PASSWORD=$RO_PW

# Local (non-Docker) connections. Compose constructs internal URLs from the
# POSTGRES_* variables; the database remains unpublished.
DATABASE_ADMIN_URL=postgresql://ssims_owner:$OWNER_PW@127.0.0.1:5432/ssims
DATABASE_URL=postgresql://ssims_app:$APP_PW@127.0.0.1:5432/ssims

DB_SSL_MODE=disable
DB_SSL_CA=
DB_SSL_SERVERNAME=localhost

JWT_ACCESS_SECRET=$JWT
COOKIE_SECRET=$COOKIE
MFA_ENCRYPTION_KEY=$MFA
CHALLENGE_SECRET=$CHALLENGE
WEBHOOK_SECRET=$WEBHOOK

ACCESS_TOKEN_TTL_SECONDS=900
REFRESH_TOKEN_TTL_DAYS=7
COOKIE_SECURE=false
TRUST_PROXY=0
EXPOSE_RESET_TOKEN=true

SEED_SUPER_ADMIN_EMAIL=superadmin@ssims.edu
SEED_SUPER_ADMIN_PASSWORD=$SUPER_PW
SEED_ADMIN_EMAIL=admin@ssims.edu
SEED_ADMIN_PASSWORD=$ADMIN_PW
SEED_LECTURER_EMAIL=lecturer@ssims.edu
SEED_LECTURER_PASSWORD=$LECTURER_PW
SEED_STUDENT_EMAIL=student@ssims.edu
SEED_STUDENT_PASSWORD=$STUDENT_PW
SEED_LAB_EMAIL=security.lab@ssims.edu
SEED_LAB_PASSWORD=$LAB_PW
EOF
chmod 600 "$TARGET"

cat <<EOF

Created .env with random secrets.

Bootstrap accounts (change these after first login):
  Super Administrator : superadmin@ssims.edu / $SUPER_PW
  Administrator       : admin@ssims.edu / $ADMIN_PW
  Lecturer            : lecturer@ssims.edu / $LECTURER_PW
  Student             : student@ssims.edu / $STUDENT_PW
  Lab target          : security.lab@ssims.edu / $LAB_PW

Docker: docker compose up --build
Local : pnpm install; pnpm migrate; pnpm seed; pnpm dev:backend; pnpm dev:frontend
EOF
