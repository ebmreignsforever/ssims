# =============================================================================
# Generate a local .env with cryptographically random secrets.
# Usage:
#   powershell -ExecutionPolicy Bypass -File scripts/generate-env.ps1
#   powershell -ExecutionPolicy Bypass -File scripts/generate-env.ps1 -Force
# =============================================================================
param([switch]$Force)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$target = Join-Path $root '.env'

if ((Test-Path $target) -and -not $Force) {
  Write-Error '.env already exists. Re-run with -Force to replace it.'
}

function New-Hex([int]$bytes = 32) {
  $buffer = New-Object -TypeName 'byte[]' -ArgumentList $bytes
  $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
  $rng.GetBytes($buffer)
  $rng.Dispose()
  return -join ($buffer | ForEach-Object { $_.ToString('x2') })
}

function New-SeedPassword([string]$prefix) {
  return "$prefix!Aa1$(New-Hex 6)"
}

$ownerPw = New-Hex 32
$appPw = New-Hex 32
$roPw = New-Hex 32
$postgresPw = New-Hex 32
$jwt = New-Hex 32
$cookie = New-Hex 32
$mfa = New-Hex 32
$challenge = New-Hex 32
$webhook = New-Hex 32
$superPw = New-SeedPassword 'SsimsSuper'
$adminPw = New-SeedPassword 'SsimsAdmin'
$lecturerPw = New-SeedPassword 'SsimsLecturer'
$studentPw = New-SeedPassword 'SsimsStudent'
$labPw = New-SeedPassword 'SsimsLab'

$content = @"
# Generated by scripts/generate-env.ps1. Never commit this file.
NODE_ENV=development
FRONTEND_ORIGIN=http://localhost:5173
ADDITIONAL_ORIGINS=https://127.0.0.1
PUBLIC_ORIGIN=https://localhost
API_PORT=4000
LOG_LEVEL=info

POSTGRES_DB=ssims
POSTGRES_USER=postgres
POSTGRES_SUPERUSER_PASSWORD=$postgresPw
POSTGRES_OWNER=ssims_owner
POSTGRES_OWNER_PASSWORD=$ownerPw
POSTGRES_APP_USER=ssims_app
POSTGRES_APP_PASSWORD=$appPw
POSTGRES_RO_PASSWORD=$roPw

# Local (non-Docker) connections. Compose constructs internal URLs from the
# POSTGRES_* variables; the database remains unpublished.
DATABASE_ADMIN_URL=postgresql://ssims_owner:$ownerPw@127.0.0.1:5432/ssims
DATABASE_URL=postgresql://ssims_app:$appPw@127.0.0.1:5432/ssims

DB_SSL_MODE=disable
DB_SSL_CA=
DB_SSL_SERVERNAME=localhost

JWT_ACCESS_SECRET=$jwt
COOKIE_SECRET=$cookie
MFA_ENCRYPTION_KEY=$mfa
CHALLENGE_SECRET=$challenge
WEBHOOK_SECRET=$webhook

ACCESS_TOKEN_TTL_SECONDS=900
REFRESH_TOKEN_TTL_DAYS=7
COOKIE_SECURE=false
TRUST_PROXY=0
EXPOSE_RESET_TOKEN=true

SEED_SUPER_ADMIN_EMAIL=superadmin@ssims.edu
SEED_SUPER_ADMIN_PASSWORD=$superPw
SEED_ADMIN_EMAIL=admin@ssims.edu
SEED_ADMIN_PASSWORD=$adminPw
SEED_LECTURER_EMAIL=lecturer@ssims.edu
SEED_LECTURER_PASSWORD=$lecturerPw
SEED_STUDENT_EMAIL=student@ssims.edu
SEED_STUDENT_PASSWORD=$studentPw
SEED_LAB_EMAIL=security.lab@ssims.edu
SEED_LAB_PASSWORD=$labPw
"@

# Write UTF-8 without a BOM so Docker Compose reads the first key cleanly.
[System.IO.File]::WriteAllText($target, $content, (New-Object System.Text.UTF8Encoding($false)))
Write-Host ''
Write-Host 'Created .env with random secrets.' -ForegroundColor Green
Write-Host ''
Write-Host 'Bootstrap accounts (change these after first login):' -ForegroundColor Yellow
Write-Host "  Super Administrator : superadmin@ssims.edu / $superPw"
Write-Host "  Administrator       : admin@ssims.edu / $adminPw"
Write-Host "  Lecturer            : lecturer@ssims.edu / $lecturerPw"
Write-Host "  Student             : student@ssims.edu / $studentPw"
Write-Host "  Lab target          : security.lab@ssims.edu / $labPw"
Write-Host ''
Write-Host 'Docker: docker compose up --build'
Write-Host 'Local : pnpm install; pnpm migrate; pnpm seed; pnpm dev:backend; pnpm dev:frontend'
